#!/usr/bin/env python3
"""Generate docs/llms.txt and docs/llms-full.txt from the mkdocs.yml navigation.

The compact file is a curated index for AI agents. The full file is a plain-text
concatenation of the pages, in navigation order.

Usage:
    python scripts/gen_llms_txt.py          # write both files
    python scripts/gen_llms_txt.py --check  # fail if the files are out of date
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path
from typing import Any, Iterable

import yaml

ROOT = Path(__file__).resolve().parent.parent
DOCS = ROOT / "docs"
MKDOCS = ROOT / "mkdocs.yml"
LLMS = DOCS / "llms.txt"
LLMS_FULL = DOCS / "llms-full.txt"
REPO_URL = "https://github.com/AeroTec-ATLAS/knowledge_base"

GENERATED_NOTE = "Generated by scripts/gen_llms_txt.py. Do not edit by hand."


class ConfigLoader(yaml.SafeLoader):
    """Safe loader that accepts MkDocs/Zensical Python tags without importing them."""


def construct_python_tag(loader: yaml.SafeLoader, tag_suffix: str, node: Any) -> Any:
    if isinstance(node, yaml.ScalarNode):
        return loader.construct_scalar(node)
    if isinstance(node, yaml.SequenceNode):
        return loader.construct_sequence(node)
    if isinstance(node, yaml.MappingNode):
        return loader.construct_mapping(node)
    return None


ConfigLoader.add_multi_constructor(
    "tag:yaml.org,2002:python/name:", construct_python_tag
)
ConfigLoader.add_multi_constructor(
    "tag:yaml.org,2002:python/object/apply:", construct_python_tag
)


def load_config() -> dict[str, Any]:
    try:
        raw = MKDOCS.read_text(encoding="utf-8")
    except OSError as exc:
        sys.exit(f"cannot read {MKDOCS}: {exc}")

    try:
        config = yaml.load(raw, Loader=ConfigLoader) or {}
    except yaml.YAMLError as exc:
        sys.exit(f"cannot parse {MKDOCS}: {exc}")

    if not isinstance(config, dict):
        sys.exit("mkdocs.yml must contain a YAML mapping")
    if not config.get("nav"):
        sys.exit("mkdocs.yml has no nav; cannot generate llms.txt")
    if not config.get("site_url"):
        sys.exit("mkdocs.yml has no site_url; cannot generate absolute links")
    return config


def split_frontmatter(text: str) -> tuple[dict[str, Any], str]:
    """Return (frontmatter, body). Handles a leading YAML block delimited by ---."""
    if not text.startswith("---"):
        return {}, text

    lines = text.splitlines(keepends=True)
    if not lines or lines[0].strip() != "---":
        return {}, text

    end = None
    for index in range(1, len(lines)):
        if lines[index].strip() == "---":
            end = index
            break

    if end is None:
        return {}, text

    raw = "".join(lines[1:end])
    body = "".join(lines[end + 1 :]).lstrip("\n")
    try:
        data = yaml.safe_load(raw) or {}
    except yaml.YAMLError:
        data = {}
    if not isinstance(data, dict):
        data = {}
    return data, body


def first_paragraph(body: str) -> str:
    """A best-effort description if frontmatter has none."""
    in_fence = False
    paragraph: list[str] = []
    for line in body.splitlines():
        stripped = line.strip()
        if stripped.startswith("```"):
            in_fence = not in_fence
            continue
        if in_fence:
            continue
        if not stripped:
            if paragraph:
                break
            continue
        if stripped.startswith("#") or stripped.startswith("!!!") or stripped.startswith("|"):
            continue
        if stripped.startswith(("---", ":::", "<!--")):
            continue
        paragraph.append(stripped)
    text = " ".join(paragraph)
    text = re.sub(r"\[([^\]]+)\]\([^)]+\)", r"\1", text)
    text = re.sub(r"[*_`>#]", "", text)
    return re.sub(r"\s+", " ", text).strip()


def flatten_nav(items: Iterable[Any], trail: tuple[str, ...] = ()) -> Iterable[tuple[tuple[str, ...], str | None, str]]:
    """Yield (trail, nav_title, path) for every page in the nav."""
    for item in items:
        if isinstance(item, str):
            yield trail, None, item
            continue
        if not isinstance(item, dict):
            continue
        for title, value in item.items():
            if isinstance(value, str):
                yield trail, title, value
            elif isinstance(value, list):
                yield from flatten_nav(value, trail + (title,))


def page_url(site_url: str, rel_path: str) -> str:
    rel = Path(rel_path)
    if rel.name == "index.md":
        parts = rel.parent.parts
    else:
        parts = rel.with_suffix("").parts
    url = site_url.rstrip("/")
    for part in parts:
        url += "/" + part
    return url + "/"


def clean_title(title: str) -> str:
    return re.sub(r"\s+", " ", title).strip()


def read_page(path: Path) -> tuple[dict[str, Any], str]:
    text = path.read_text(encoding="utf-8")
    return split_frontmatter(text)


def generate(config: Any) -> tuple[str, str]:
    site_url = str(config["site_url"]).rstrip("/")
    description = re.sub(r"\s+", " ", str(config.get("site_description") or "")).strip()

    pages: list[dict[str, Any]] = []
    seen: set[str] = set()

    for trail, nav_title, rel_path in flatten_nav(config["nav"]):
        if not rel_path.endswith(".md"):
            continue
        if rel_path in seen:
            continue
        seen.add(rel_path)

        path = DOCS / rel_path
        if not path.exists():
            sys.exit(f"nav points to a missing file: {rel_path}")

        frontmatter, body = read_page(path)
        title = clean_title(str(frontmatter.get("title") or nav_title or Path(rel_path).stem))
        desc = str(frontmatter.get("description") or first_paragraph(body)).strip()
        desc = re.sub(r"\s+", " ", desc)

        # The first nav level is the section; the root page is "Home".
        if rel_path == "index.md":
            section = "Home"
        else:
            section = trail[0] if trail else title
        breadcrumb = trail[1:] if len(trail) > 1 else ()
        # A section index page has the same title as its section; do not repeat it.
        if breadcrumb and breadcrumb[-1] == title:
            breadcrumb = breadcrumb[:-1]
        label = " / ".join([*breadcrumb, title]) if breadcrumb else title

        pages.append(
            {
                "path": rel_path,
                "title": title,
                "description": desc,
                "section": section,
                "label": label,
                "url": page_url(site_url, rel_path),
                "body": body,
            }
        )

    # --- compact index -------------------------------------------------
    out: list[str] = [
        "# ATLAS Knowledge Base",
        "",
        f"> {description}",
        "",
        f"<!-- {GENERATED_NOTE} -->",
        "",
    ]

    sections: dict[str, list[dict[str, Any]]] = {}
    for page in pages:
        sections.setdefault(page["section"], []).append(page)

    for section, section_pages in sections.items():
        out.append(f"## {section}")
        out.append("")
        for page in section_pages:
            line = f"- [{page['label']}]({page['url']})"
            if page["description"]:
                line += f": {page['description']}"
            out.append(line)
        out.append("")

    out.extend(
        [
            "## Optional",
            "",
            f"- [Full text]({site_url}/llms-full.txt): every page concatenated in navigation order.",
            f"- [AGENTS.md]({REPO_URL}/blob/main/AGENTS.md): rules for AI agents editing this repository.",
            f"- [CONTRIBUTING.md]({REPO_URL}/blob/main/CONTRIBUTING.md): how humans add and review pages.",
            "",
        ]
    )
    compact = "\n".join(out).rstrip() + "\n"

    # --- full text ------------------------------------------------------
    full: list[str] = [
        "# ATLAS Knowledge Base — full text",
        "",
        f"> {description}",
        "",
        f"<!-- {GENERATED_NOTE} -->",
        "",
    ]
    for page in pages:
        body = re.sub(r"\A# .*\n+", "", page["body"]).strip()
        full.append(f"## {page['label']}")
        full.append("")
        full.append(f"Source: {page['url']}")
        full.append("")
        full.append(body)
        full.append("")
        full.append("---")
        full.append("")
    full_text = "\n".join(full).rstrip() + "\n"

    return compact, full_text


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="fail if docs/llms.txt or docs/llms-full.txt are out of date",
    )
    args = parser.parse_args()

    config = load_config()
    compact, full_text = generate(config)

    if args.check:
        errors = []
        for path, expected in ((LLMS, compact), (LLMS_FULL, full_text)):
            if not path.exists():
                errors.append(f"missing: {path.relative_to(ROOT)}")
            elif path.read_text(encoding="utf-8") != expected:
                errors.append(f"out of date: {path.relative_to(ROOT)}")
        if errors:
            print("AI index is not up to date:", file=sys.stderr)
            for error in errors:
                print(f"  - {error}", file=sys.stderr)
            print("Run: python scripts/gen_llms_txt.py", file=sys.stderr)
            return 1
        print("AI index is up to date.")
        return 0

    LLMS.write_text(compact, encoding="utf-8")
    LLMS_FULL.write_text(full_text, encoding="utf-8")
    print(f"wrote {LLMS.relative_to(ROOT)} ({len(compact)} bytes)")
    print(f"wrote {LLMS_FULL.relative_to(ROOT)} ({len(full_text)} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
